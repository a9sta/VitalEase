import { josa } from '../lib/util.mjs';

/** 뭉침 정도를 말로 — 1 에 가까울수록 동그랗다. */
export function edgeWord(r) {
  if (r >= 0.66) return '둘레가 동그랗게 뭉쳐 있는';
  if (r >= 0.46) return '둘레가 비교적 고른';
  if (r >= 0.28) return '둘레가 구불구불한';
  return '둘레가 길게 갈라진';
}
/** 안쪽 깊이를 말로 — 큰길에서 집까지 남는 거리가 얼마나 되는지. */
export function depthNote(km) {
  if (km < 0.25) return '어느 집이든 큰길에서 몇 걸음이면 닿습니다';
  if (km < 0.6) return '가장 안쪽 집도 걸어 들어갈 만합니다';
  if (km < 1.2) return '안쪽까지 들어가면 차로 몇 분이 더 붙습니다';
  return '안쪽 끝까지는 한참 들어가야 합니다';
}

